// Writes plugin/Source/dsp/Params.gen.h from src/dsp/params.ts (and the
// factory presets from presets.ts): the flat parameter list, the matrix
// tables and the presets, so the C++ engine and the host see exactly what
// the web version sees. Run after changing params.ts or presets.ts:
//
//   node scripts/gen-plugin.ts

import { writeFileSync, mkdirSync } from 'node:fs';
import * as params from '../src/dsp/params.ts';
import { PRESETS } from '../src/dsp/presets.ts';
import { ARP_BEATS } from '../src/dsp/arp.ts';

const { PARAMS, DESTS, GLOBAL_SOURCE, DIV_BEATS, SOURCES, MATRIX_SLOTS } = params;

const out = 'plugin/Source/dsp/Params.gen.h';
const idx = new Map(PARAMS.map((p, i) => [p.id, i]));
const num = (x: number) => {
  const s = String(x);
  return /[.e]/.test(s) ? s : `${s}.0`;
};
const str = (s: string | undefined) => (s === undefined ? 'nullptr' : JSON.stringify(s));
const SCALE = { lin: 'Lin', log: 'Log', int: 'Int', enum: 'Enum', bool: 'Bool' } as const;

const L: string[] = [];
L.push('// Generated by scripts/gen-plugin.ts from src/dsp/params.ts and presets.ts. Do not edit.');
L.push('#pragma once');
L.push('');
L.push('namespace prism {');
L.push('');
L.push('enum class Scale { Lin, Log, Int, Enum, Bool };');
L.push('');
L.push('struct ParamDef {');
L.push('  const char* id; const char* name; const char* group;');
L.push('  double min, max, def; Scale scale; const char* unit;');
L.push('  const char* const* labels; int numLabels;');
L.push('};');
L.push('');
L.push('namespace P {');
L.push('enum : int {');
for (const p of PARAMS) L.push(`  ${p.id},`);
L.push('  COUNT');
L.push('};');
L.push('}');
L.push('');
L.push('constexpr int NUM_PARAMS = P::COUNT;');
L.push('');
PARAMS.forEach((p) => {
  if (p.labels) L.push(`inline constexpr const char* LABELS_${p.id}[] = { ${p.labels.map((l) => JSON.stringify(l)).join(', ')} };`);
});
L.push('');
L.push('inline constexpr ParamDef PARAMS[NUM_PARAMS] = {');
for (const p of PARAMS) {
  const labels = p.labels ? `LABELS_${p.id}, ${p.labels.length}` : 'nullptr, 0';
  L.push(`  { ${str(p.id)}, ${str(p.name)}, ${str(p.group)}, ${num(p.min)}, ${num(p.max)}, ${num(p.def)}, Scale::${SCALE[p.scale]}, ${str(p.unit)}, ${labels} },`);
}
L.push('};');
L.push('');

// the numeric constants of params.ts (S_ENV1, D_PITCH, W_FORMANT, F_LP24, I_RING, STEPS …)
L.push('// constants from params.ts');
for (const [name, v] of Object.entries(params)) {
  if (typeof v === 'number' && /^[A-Z][A-Z0-9_]*$/.test(name)) L.push(`constexpr int ${name} = ${v};`);
}
L.push(`constexpr int N_SOURCES = ${SOURCES.length};`);
L.push(`/** osc n's (0-based) first destination: then +0 position, +1 warp, +2 level, +3 pitch, +4 detune, +5 pan */`);
L.push(`constexpr int D_OSC(int n) { return ${params.D_OSC(0)} + n * ${params.D_OSC(1) - params.D_OSC(0)}; }`);
L.push('');
L.push(`inline constexpr double DEST_RANGE[N_DESTS] = { ${DESTS.map((d) => num(d.range)).join(', ')} };`);
L.push(`inline constexpr bool DEST_GLOBAL[N_DESTS] = { ${DESTS.map((d) => (d.global ? 'true' : 'false')).join(', ')} };`);
L.push(`inline constexpr bool GLOBAL_SOURCE[N_SOURCES] = { ${GLOBAL_SOURCE.map((g) => (g ? 'true' : 'false')).join(', ')} };`);
L.push(`inline constexpr double DIV_BEATS[] = { ${DIV_BEATS.map(num).join(', ')} };`);
L.push(`constexpr int NUM_DIVS = ${DIV_BEATS.length};`);
L.push(`inline constexpr double ARP_BEATS[] = { ${ARP_BEATS.map(num).join(', ')} };`);
L.push(`constexpr int NUM_ARP_RATES = ${ARP_BEATS.length};`);
const slots = Array.from({ length: MATRIX_SLOTS }, (_, i) => i + 1);
L.push(`inline constexpr int MATRIX_SRC[MATRIX_SLOTS] = { ${slots.map((i) => `P::m${i}Src`).join(', ')} };`);
L.push(`inline constexpr int MATRIX_DST[MATRIX_SLOTS] = { ${slots.map((i) => `P::m${i}Dst`).join(', ')} };`);
L.push(`inline constexpr int MATRIX_AMT[MATRIX_SLOTS] = { ${slots.map((i) => `P::m${i}Amt`).join(', ')} };`);
L.push(`inline constexpr int MATRIX_VIA[MATRIX_SLOTS] = { ${slots.map((i) => `P::m${i}Via`).join(', ')} };`);
L.push('');

// the stepper cells: which table and cell a parameter is, or -1
L.push('/** For a stepper cell parameter: which stepper (0, 1), else -1; and which cell. */');
L.push(`inline constexpr signed char CELL_TAB[NUM_PARAMS] = { ${PARAMS.map((p) => (p.tab ? (p.tab === 's1' ? 0 : 1) : -1)).join(', ')} };`);
L.push(`inline constexpr signed char CELL_IDX[NUM_PARAMS] = { ${PARAMS.map((p) => p.idx ?? -1).join(', ')} };`);
L.push('/** For a macro parameter: which macro (0..7), else -1. */');
L.push(`inline constexpr signed char MACRO_IDX[NUM_PARAMS] = { ${PARAMS.map((p) => (p.id.startsWith('macro') ? Number(p.id.slice(5)) - 1 : -1)).join(', ')} };`);
L.push('');

L.push('struct PresetValue { int id; double value; };');
L.push('struct Preset { const char* name; const char* tag; const PresetValue* values; int count; };');
L.push('');
PRESETS.forEach((pr, i) => {
  const vals = Object.entries(pr.values).map(([id, v]) => {
    if (idx.get(id) === undefined) throw new Error(`preset "${pr.name}": unknown param ${id}`);
    return `{ P::${id}, ${num(v!)} }`;
  });
  // an empty preset (init) has no array: C++ has no zero-length ones
  if (vals.length) L.push(`inline constexpr PresetValue PRESET_${i}[] = { ${vals.join(', ')} };`);
});
L.push('');
L.push(`constexpr int NUM_PRESETS = ${PRESETS.length};`);
L.push('inline constexpr Preset PRESETS[NUM_PRESETS] = {');
PRESETS.forEach((pr, i) => L.push(`  { ${str(pr.name)}, ${str(pr.tag)}, ${Object.keys(pr.values).length ? `PRESET_${i}` : 'nullptr'}, ${Object.keys(pr.values).length} },`));
L.push('};');
L.push('');
L.push('} // namespace prism');
L.push('');

mkdirSync('plugin/Source/dsp', { recursive: true });
writeFileSync(out, L.join('\n'));
console.log(`wrote ${out}: ${PARAMS.length} params, ${PRESETS.length} presets`);
